"""Build and persist separate ChromaDB indexes for each chunking strategy."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from knowledge_base.loader import load_knowledge_base
from rag.chunking import chunk_by_sentence, chunk_fixed_size
from rag.embeddings import EMBEDDING_MODEL_NAME, LocalEmbeddingService

DEFAULT_PERSIST_DIRECTORY = Path(__file__).resolve().parents[1] / "chroma_db"
FIXED_COLLECTION = "ola_support_fixed"
SENTENCE_COLLECTION = "ola_support_sentence"
PROJECT_COLLECTIONS = (FIXED_COLLECTION, SENTENCE_COLLECTION)


def _persistent_client(persist_directory: str | Path | None = None) -> Any:
    try:
        import chromadb
    except ImportError as error:
        raise RuntimeError(
            "ChromaDB is required for vector indexing; install the project requirements."
        ) from error

    path = Path(persist_directory or DEFAULT_PERSIST_DIRECTORY).expanduser().resolve()
    path.mkdir(parents=True, exist_ok=True)
    return chromadb.PersistentClient(path=str(path))


def _ensure_cosine_collection(client: Any, name: str) -> Any:
    collection = client.get_or_create_collection(
        name=name,
        metadata={"hnsw:space": "cosine"},
    )
    if (collection.metadata or {}).get("hnsw:space") != "cosine":
        raise ValueError(
            f"Collection {name!r} must use cosine distance; rebuild it with reset=True."
        )
    return collection


def _upsert_chunks(
    collection: Any,
    chunks: list[dict[str, str | int]],
    embeddings: list[list[float]],
    strategy: str,
) -> int:
    if len(chunks) != len(embeddings):
        raise ValueError("Every chunk must have exactly one embedding.")

    chunk_ids = [str(chunk["chunk_id"]) for chunk in chunks]
    collection.upsert(
        ids=chunk_ids,
        embeddings=embeddings,
        documents=[str(chunk["text"]) for chunk in chunks],
        metadatas=[
            {
                key: chunk[key]
                for key in (
                    "document_id",
                    "parent_title",
                    "topic",
                    "filename",
                    "chunk_index",
                    "chunk_strategy",
                )
            }
            for chunk in chunks
        ],
    )

    # Remove stale IDs generated by this strategy if source documents changed.
    existing_ids = collection.get(include=[])["ids"]
    current_ids = set(chunk_ids)
    stale_ids = [
        item_id
        for item_id in existing_ids
        if re.fullmatch(rf"KB-\d{{3}}-{re.escape(strategy)}-\d{{3}}", item_id)
        and item_id not in current_ids
    ]
    if stale_ids:
        collection.delete(ids=stale_ids)
    return collection.count()


def build_indexes(
    reset: bool = False,
    persist_directory: str | Path | None = None,
    embedding_service: LocalEmbeddingService | None = None,
) -> dict[str, Any]:
    """Load, chunk, embed, and upsert both project indexes independently."""
    client = _persistent_client(persist_directory)
    existing_names = {
        item.name for item in client.list_collections()
    }
    if reset:
        for name in PROJECT_COLLECTIONS:
            if name in existing_names:
                client.delete_collection(name)

    documents = load_knowledge_base()
    fixed_chunks = chunk_fixed_size(documents)
    sentence_chunks = chunk_by_sentence(documents)
    embeddings = embedding_service or LocalEmbeddingService()

    fixed_collection = _ensure_cosine_collection(client, FIXED_COLLECTION)
    sentence_collection = _ensure_cosine_collection(client, SENTENCE_COLLECTION)
    fixed_vectors = embeddings.embed_documents(
        [str(chunk["text"]) for chunk in fixed_chunks]
    )
    sentence_vectors = embeddings.embed_documents(
        [str(chunk["text"]) for chunk in sentence_chunks]
    )

    fixed_count = _upsert_chunks(
        fixed_collection, fixed_chunks, fixed_vectors, "fixed"
    )
    sentence_count = _upsert_chunks(
        sentence_collection, sentence_chunks, sentence_vectors, "sentence"
    )

    return {
        "embedding_model": embeddings.model_name,
        "documents_loaded": len(documents),
        "fixed": {
            "chunks_created": len(fixed_chunks),
            "collection": FIXED_COLLECTION,
            "stored_records": fixed_count,
        },
        "sentence": {
            "chunks_created": len(sentence_chunks),
            "collection": SENTENCE_COLLECTION,
            "stored_records": sentence_count,
        },
    }


def main() -> None:
    """Build both indexes and report their actual sizes."""
    stats = build_indexes()
    print(f"Embedding model:\n{stats['embedding_model']}")
    print(f"\nDocuments loaded: {stats['documents_loaded']}")
    for strategy, label in (("fixed", "Fixed-size"), ("sentence", "Sentence")):
        info = stats[strategy]
        print(f"\n{label} strategy:")
        print(f"Chunks created: {info['chunks_created']}")
        print(f"Collection: {info['collection']}")
        print(f"Stored records: {info['stored_records']}")


if __name__ == "__main__":
    main()
